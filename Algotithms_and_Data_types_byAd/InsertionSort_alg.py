# Сортировка вставками
# Сложность алгоритма O(n2) - квадратичная, количество необходимых операций растет квадратично n2
# Алгоритм имеет преимущество, если в уже отсортированный массив добавляются еще элементы,
# То не нужно сортировать все элементы заново, достаточно поставить на нужно место, новые элементы
#Позволяет досортировывать массивы при появлении новых элементов

# Сортировка вставками досортировывает почти отсортированные массивы быстро потому что:
# Каждый новый элемент сравнивается только с соседями в отсортированной части
# Если элемент уже на своем месте (больше предыдущего), проверка занимает O(1)
# В среднем для почти отсортированного массива нужно O(k) операций на элемент, где k — среднее расстояние до правильной позиции
# Эффективность в разных случаях:
# Лучший случай (уже отсортирован): O(n) — только n-1 сравнение
# Почти отсортированный: O(n + k) где k мало
# Случайный массив: O(n²)
# Худший случай (обратно отсортирован): O(n²)


def insertion_sort(array):
    for i in range(1, len(array)):
        for j in range(i, 0, -1):
            if array[j] < array[j - 1]:
                array[j], array[j - 1] = array[j - 1], array[j]
            else:
                break
    return array


unsort_ar = [4, 2, 6, 1, 3]
print(insertion_sort(unsort_ar))
