# Алгоритм Дейкстры работает с направленными ациклическими графами с неотрицательными весами(работает со взвешенными графами с неотрицательными весами).
# Вес - это какой-то критерий
# Алгоритм Дейкстры — это метод поиска кратчайших путей от одной вершины графа до всех остальных.
# Он работает с взвешенными графами, где веса рёбер неотрицательны, и использует «жадную» стратегию:
# на каждом шаге выбирает вершину с наименьшим текущим расстоянием от начальной точки.