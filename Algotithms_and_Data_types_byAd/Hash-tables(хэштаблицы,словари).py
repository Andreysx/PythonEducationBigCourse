# Базовая структура данных - ХЕШ-ТАБЛИЦА
# Хеш-таблица(dict) = хеш-функция + массив
# Хеш-таблица состоит из ключей и значений, связывает ключи и значения
#
# Хэш-таблицы используют массив для хранения данных.
# Хэш-таблицы используют для моделирования отношений между объектами (ключ-значение)
# Хэш-таблицы используют для устранение дубликатов
# Хэш-таблицы используют для кэширование
#
# Хэш таблицы обеспечивают высоку скорость операций - чтение(поиск), запись, удаление.

# Быстродействие хеш-функции зависит от избежания коллизий(когда разные ключи дают одинаковый хеш), для этого необходимы:
# 1) Кооэффициент заполнения функции(количество элементов таблицы/общее количество элементов) < 0.7
# С меньшим коэффициентом загрузки число коллизий уменьшается, и хеш-таблица работет более эффективно.
# Изменяйте размер таблицы(массива) когда коэф заполнения превышает 0.7
# 2)Хорошая хеш-функция(SHA etc...)
# Хеш-функция отображает строки на числа
# Хеш-функция должа быть последовательна(идемпотентна - неизменно возвращает один и тот же результат для одинаковых входных данных)
# Хорошая хеш-функция должна обеспечивать равномерное распределение значений в массиве
# Плохая хеш-функция создает скопления и порождает множество коллизий.
# Хеш-функции должны обеспечивать хорошее распределение ,как можно шире(не кластеризируя их )
# Худший случай - хеш-функция отображает все значения на одну позицию в хеш таблице(массиве)

#
# Средний случай O(1) хорошая хеш-функция - хороший коэффициет заполнения
# Худший случай O(n) все отображается на 1 элемент массива(в нем создается связный список)



# В Python коллизии в хеш-функциях (когда разные ключи дают одинаковый хеш) решаются с помощью двух основных методов:
#
# Открытая адресация (Open Addressing) — при коллизии интерпретатор ищет следующий свободный слот в хеш-таблице, используя последовательный перебор (линейное пробирование),
# квадратичное пробирование или двойное хеширование.
# Например, если хеш для ключа занят, проверяется следующий индекс, и так далее, пока не найдётся свободное место13.
#
# Метод цепочек (Chaining) — каждый слот хеш-таблицы содержит связанный список (или другую структуру), в котором хранятся все элементы с одинаковым хешем.
# Если возникает коллизия, новый элемент просто добавляется в этот список38.
#
# В реализации словарей Python используется открытая адресация с линейным пробированием и дополнительными оптимизациями для быстрого поиска и вставки.
# Это позволяет эффективно обрабатывать коллизии без значительного ухудшения производительности13.
#
# Таким образом, при столкновении нескольких ключей с одинаковым хешем Python либо ищет следующий свободный слот (открытая адресация),
# либо хранит все элементы с одним хешем в списке (цепочки), чтобы обеспечить корректную работу словарей и множеств.
