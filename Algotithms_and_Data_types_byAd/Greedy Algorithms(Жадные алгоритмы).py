# Жадные алгоритмы (Greedy Algorithms) — это класс алгоритмов(приближенные алгоритмы),
# которые принимают локально оптимальные решения на каждом шаге в надежде найти глобально оптимальное решение.
#
# Основная идея
# На каждом шаге алгоритм выбирает наилучший вариант в данный момент, не заботясь о будущих последствиях.
#
# Ключевые характеристики:
# Локальная оптимальность: Выбор лучшего варианта на текущем шаге
#
# Безвозвратность: Принятые решения не пересматриваются
#
# Эффективность: Обычно имеют низкую временную сложность
#
#
# Задача о рюкзаке (дробный вариант)
# Алгоритм Дейкстры (кратчайший путь)
# Поиск в ширину
#
#
# Преимущества и недостатки
# ✅ Преимущества:
# Простота реализации
#
# Высокая эффективность (обычно O(n log n) или O(n))
#
# Минимальное использование памяти
#
# ❌ Недостатки:
# Не всегда находят оптимальное решение
#
# Применимы только к определенным типам задач
#
# Требуют доказательства корректности